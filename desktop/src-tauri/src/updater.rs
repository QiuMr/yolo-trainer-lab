//! Automatic updates via GitHub Releases, using `tauri-plugin-updater`.
//!
//! # Why not the hand-rolled updater from OCR-Studio
//!
//! That project ships a portable zip with `bundle.active = false`, so "update" means "overwrite
//! the install directory with a newer zip". This app ships an **NSIS installer** and registers
//! uninstall entries, so overwriting files would leave the registry pointing at a version that
//! no longer exists. The official plugin downloads the signed `.nsis.zip`, verifies its
//! minisign signature and launches the real installer in passive mode — the registry, the
//! `externalBin` engine and the uninstaller all stay consistent.
//!
//! It also removes the two hardest bugs from the portable approach: a helper process that has to
//! run before the single-instance plugin, and waiting for DLL handles to be released before
//! overwriting. The installer handles both.
//!
//! # Feed
//!
//! `endpoints` in tauri.conf.json points at `releases/latest/download/latest.json`, a **fixed**
//! URL that GitHub redirects to the newest non-draft Release. No client-side change is ever
//! needed to publish a new version. The manifest is generated by `scripts/release.ps1`; the
//! private signing key lives outside the repository.
//!
//! # Errors are data, not exceptions
//!
//! No network, a not-yet-published feed and a corporate proxy are normal states, not broken app
//! states. `check()` folds every failure into `UpdateInfo.error` so the settings page can show a
//! plain sentence instead of a red error dialog.

use std::cmp::Ordering;

use serde::Serialize;
use tauri::{AppHandle, Emitter};
use tauri_plugin_updater::{Error as UpdaterError, UpdaterExt};

/// Progress events emitted while downloading/installing. Consumed by `components/UpdateCard.tsx`.
pub const PROGRESS_EVENT: &str = "update-progress";

/// What the settings page needs to know. Deliberately small: no URLs, no signatures, no raw JSON.
#[derive(Debug, Clone, Serialize)]
pub struct UpdateInfo {
    pub current: String,
    /// Equals `current` when there is no update, so the UI never renders an empty version chip.
    pub latest: String,
    pub has_update: bool,
    pub notes: String,
    /// `None` means the check succeeded. A populated string means "could not check", which is
    /// different from "no update" and must not be shown as such.
    pub error: Option<String>,
}

impl UpdateInfo {
    fn unchanged(current: &str) -> Self {
        Self {
            current: current.to_owned(),
            latest: current.to_owned(),
            has_update: false,
            notes: String::new(),
            error: None,
        }
    }
}

/// Turn upstream errors into one readable sentence. `ReleaseNotFound` is the state of a project
/// that has not published its first Release yet — not a fault.
fn friendly(error: &UpdaterError) -> String {
    match error {
        UpdaterError::ReleaseNotFound => "更新源还没有发布记录".to_owned(),
        UpdaterError::UnsupportedOs | UpdaterError::UnsupportedArch => {
            "当前系统不支持自动更新，请到 GitHub Releases 手动下载".to_owned()
        }
        UpdaterError::Network(message) => format!("连不上更新服务器：{message}"),
        UpdaterError::Reqwest(inner) if inner.is_timeout() => {
            "连不上更新服务器（超时）。检查网络后再试".to_owned()
        }
        UpdaterError::Reqwest(inner) if inner.is_connect() => {
            "连不上更新服务器。如果是公司网络，可能需要配代理".to_owned()
        }
        UpdaterError::TargetNotFound(_) | UpdaterError::TargetsNotFound(_) => {
            "更新源里没有适用于当前系统的安装包".to_owned()
        }
        other => format!("检查更新失败：{other}"),
    }
}

/// Query the feed. Never panics and never returns `Err` — see the module doc.
pub async fn check(app: &AppHandle) -> UpdateInfo {
    let current = crate::version::VERSION;
    let updater = match app.updater() {
        Ok(updater) => updater,
        Err(error) => {
            let mut info = UpdateInfo::unchanged(current);
            info.error = Some(format!("更新组件未就绪：{error}"));
            return info;
        }
    };

    match updater.check().await {
        // The plugin already applied its semver comparator; `Some` means "newer than current".
        Ok(Some(update)) => UpdateInfo {
            current: current.to_owned(),
            latest: update.version,
            has_update: true,
            notes: update.body.unwrap_or_default(),
            error: None,
        },
        Ok(None) => UpdateInfo::unchanged(current),
        Err(error) => {
            let mut info = UpdateInfo::unchanged(current);
            info.error = Some(friendly(&error));
            info
        }
    }
}

/// Download, verify and launch the installer.
///
/// We re-check the feed here rather than caching the `Update` from `check()`: minutes may have
/// passed since the user opened the settings page, and holding a `Update` in global state would
/// require it to be `Send + Sync` for no benefit. One extra HTTPS GET is cheaper than installing
/// a release that was superseded while the window sat open.
///
/// On Windows a successful `download_and_install` **exits this process** after starting the
/// installer, so the `Ok(())` below is normally never observed by the frontend. The
/// `installing` progress event is the last thing the UI sees.
pub async fn install(app: &AppHandle) -> Result<(), String> {
    let updater = app
        .updater()
        .map_err(|error| format!("更新组件未就绪：{error}"))?;
    let update = updater
        .check()
        .await
        .map_err(|error| friendly(&error))?
        .ok_or_else(|| "已经是最新版本，不需要更新".to_owned())?;

    // Defence in depth: an endpoint JSON copied from an older tag could otherwise pair an old
    // (validly signed) artifact with a newer version string. The plugin's comparator is trusted,
    // but this makes a misconfigured feed fail loudly instead of silently downgrading.
    if crate::version::cmp_version(&update.version, crate::version::VERSION) != Ordering::Greater {
        return Err(format!(
            "更新源指向 v{}，不比当前 v{} 新，已中止。请检查 Release 的 latest.json。",
            update.version,
            crate::version::VERSION
        ));
    }

    // Two handles because both callbacks must own their emitter; one is FnMut, the other FnOnce.
    let on_chunk_app = app.clone();
    let on_done_app = app.clone();
    let mut downloaded = 0u64;
    let mut last_percent: i64 = -1;

    update
        .download_and_install(
            move |chunk: usize, total: Option<u64>| {
                downloaded += chunk as u64;
                // Emitting per 8 KB chunk would flood the webview. One event per percent is
                // plenty; -1 means the server did not send Content-Length.
                let percent = total
                    .filter(|value| *value > 0)
                    .map(|value| (downloaded * 100 / value) as i64)
                    .unwrap_or(-1);
                if percent == last_percent {
                    return;
                }
                last_percent = percent;
                let _ = on_chunk_app.emit(
                    PROGRESS_EVENT,
                    serde_json::json!({ "phase": "downloading", "percent": percent }),
                );
            },
            move || {
                let _ = on_done_app.emit(
                    PROGRESS_EVENT,
                    serde_json::json!({ "phase": "installing", "percent": 100 }),
                );
            },
        )
        .await
        .map_err(|error| format!("下载或安装更新失败：{error}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn unchanged_is_not_an_update_and_has_no_error() {
        let info = UpdateInfo::unchanged("0.1.0");
        assert_eq!(info.current, "0.1.0");
        assert_eq!(info.latest, "0.1.0");
        assert!(!info.has_update);
        assert!(info.error.is_none());
    }

    #[test]
    fn missing_release_is_a_friendly_sentence_not_a_raw_error() {
        let message = friendly(&UpdaterError::ReleaseNotFound);
        assert!(message.contains("还没有发布记录"));
        assert!(!message.contains("ReleaseNotFound"));
    }

    /// The UI branches on `error`; a JSON payload with a null error must still round-trip.
    #[test]
    fn info_serializes_with_snake_case_keys() {
        let value = serde_json::to_value(UpdateInfo::unchanged("1.2.3")).unwrap();
        assert_eq!(value["has_update"], false);
        assert_eq!(value["current"], "1.2.3");
        assert!(value["error"].is_null());
        assert!(value.get("hasUpdate").is_none());
    }
}
